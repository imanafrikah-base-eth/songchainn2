-- Stream history: the counts the catalogue carried before plays were recorded.
--
-- Until now every song's stream count was a number the client computed on
-- every load: a per-artist total in musicData.ts, split across that artist's
-- songs by a hash, with the real plays from song_analytics added on top. The
-- numbers people saw were stable, but they lived in a formula in the bundle,
-- and the formula was the only place they lived.
--
-- This moves those exact numbers, song by song, into the database as a
-- starting balance. The formula and the per-artist totals are deleted from the
-- client. From here on a song's count is one thing: this row plus every real
-- play in song_analytics. The counter goes up the normal way and nothing is
-- seeded again. get_song_popularity() is the single place the sum happens.
--
-- 234 songs, 263,140 plays in total, captured 6 September 2026 from the
-- distribution as it stood in the last deployed bundle. Nobody typed these.
--
-- Nothing on the client may write here. The table is read by one SQL function
-- and by nothing else.

create table if not exists public.song_stream_history (
  song_id text primary key,
  plays integer not null check (plays >= 0),
  note text,
  recorded_at timestamptz not null default now()
);

alter table public.song_stream_history enable row level security;

drop policy if exists "stream history is readable" on public.song_stream_history;
create policy "stream history is readable"
  on public.song_stream_history for select
  to anon, authenticated
  using (true);

